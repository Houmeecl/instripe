#!/usr/bin/env node

import { createHash } from "node:crypto";
import { existsSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const [sourcePath, outputPath] = process.argv.slice(2);

if (!sourcePath || !outputPath || process.argv.length !== 4) {
  console.error("Usage: node scripts/export-sqlite-to-postgres.mjs <source.sqlite> <migration.sql>");
  process.exit(1);
}

const source = path.resolve(sourcePath);
const output = path.resolve(outputPath);
if (!existsSync(source)) {
  console.error(`SQLite database does not exist: ${source}`);
  process.exit(1);
}
if (source === output) {
  console.error("The SQLite source and SQL output paths must differ");
  process.exit(1);
}
if (existsSync(output)) {
  console.error(`Refusing to overwrite existing migration file: ${output}`);
  process.exit(1);
}

const require = createRequire(import.meta.url);
const sqlite = require("node:sqlite");
const database = new sqlite.DatabaseSync(source, { readOnly: true });

try {
  const rows = database
    .prepare("SELECT rowid AS position, collection, id, body FROM records ORDER BY rowid ASC")
    .all();
  for (const row of rows) {
    try {
      JSON.parse(row.body);
    } catch {
      throw new Error(`Invalid JSON in records(${row.collection}, ${row.id})`);
    }
  }

  const checksum = createHash("sha256")
    .update(JSON.stringify(rows))
    .digest("hex");
  const statements = rows.map(
    (row) =>
      `INSERT INTO records (position, collection, id, body) OVERRIDING SYSTEM VALUE VALUES (${Number(row.position)}, ${sqlLiteral(row.collection)}, ${sqlLiteral(row.id)}, ${sqlLiteral(row.body)}::jsonb);`,
  );
  const sql = [
    "-- Generated by scripts/export-sqlite-to-postgres.mjs",
    `-- Source record count: ${rows.length}`,
    `-- Source SHA-256: ${checksum}`,
    "-- Run once against an empty target database with psql -v ON_ERROR_STOP=1.",
    "BEGIN;",
    "",
    "CREATE TABLE IF NOT EXISTS records (",
    "  collection TEXT NOT NULL,",
    "  id TEXT NOT NULL,",
    "  body JSONB NOT NULL,",
    "  position BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,",
    "  PRIMARY KEY (collection, id)",
    ");",
    "",
    "CREATE INDEX IF NOT EXISTS records_collection_position_idx ON records (collection, position);",
    "",
    "LOCK TABLE records IN ACCESS EXCLUSIVE MODE;",
    "DO $migration$",
    "BEGIN",
    "  IF EXISTS (SELECT 1 FROM records LIMIT 1) THEN",
    "    RAISE EXCEPTION 'Target records table is not empty; refusing migration';",
    "  END IF;",
    "END",
    "$migration$;",
    "",
    ...statements,
    "",
    `DO $verification$`,
    "BEGIN",
    `  IF (SELECT COUNT(*) FROM records) <> ${rows.length} THEN`,
    "    RAISE EXCEPTION 'Record count verification failed';",
    "  END IF;",
    "END",
    "$verification$;",
    "",
    "SELECT setval(pg_get_serial_sequence('records', 'position'), COALESCE(MAX(position), 1), COUNT(*) > 0) FROM records;",
    "",
    "COMMIT;",
    "",
  ].join("\n");

  const temporaryOutput = `${output}.${process.pid}.tmp`;
  writeFileSync(temporaryOutput, sql, { encoding: "utf8", mode: 0o600, flag: "wx" });
  renameSync(temporaryOutput, output);
  console.log(`Exported ${rows.length} records to ${output}`);
  console.log(`Source SHA-256: ${checksum}`);
} finally {
  database.close();
}

function sqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}
